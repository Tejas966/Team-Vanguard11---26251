"""Re-fetch the real weather snapshot used by the web prototype.

Source: Open-Meteo.com (ERA5 reanalysis archive + forecast API), CC BY 4.0, free non-commercial tier, no API key.
Points: three public civilian grid points in the western Himalaya, labelled W1-W3 in the app.
They are not linked to any military site. Output: web/js/weather-data.js

Usage:  python data/fetch_weather.py
"""
import datetime, json, urllib.request

LAT, LON, TZ = [34.16, 34.56, 32.23], [77.58, 76.13, 78.07], "Asia/Kolkata"
LABELS = [("W1", "Upper Indus valley cell", "high-altitude cold desert"),
          ("W2", "Lower valley cell", "lower, milder valley"),
          ("W3", "High plateau cell", "highest, snowiest cell")]
ARCHIVE, FORECAST = "https://archive-api.open-meteo.com/v1/archive", "https://api.open-meteo.com/v1/forecast"
coords = f"latitude={','.join(map(str, LAT))}&longitude={','.join(map(str, LON))}&timezone={TZ.replace('/', '%2F')}"

def get(url):
    with urllib.request.urlopen(url, timeout=60) as r:
        return json.load(r)

end = (datetime.date.today() - datetime.timedelta(days=7)).isoformat()   # archive lags a few days
hist = get(f"{ARCHIVE}?{coords}&start_date=2023-01-01&end_date={end}"
           "&daily=temperature_2m_min,temperature_2m_max,snowfall_sum,precipitation_sum")
fc = get(f"{FORECAST}?{coords}&forecast_days=16"
         "&daily=temperature_2m_min,temperature_2m_max,snowfall_sum,precipitation_sum,wind_speed_10m_max")
r = lambda a: [None if x is None else round(x, 1) for x in a]
cells = []
for (cid, label, note), h, f in zip(LABELS, hist, fc):
    hd, fd = h["daily"], f["daily"]
    cells.append({"id": cid, "label": label, "note": note, "lat": round(h["latitude"], 2), "lon": round(h["longitude"], 2),
                  "elev": h["elevation"],
                  "hist": {"t0": hd["time"][0], "tmin": r(hd["temperature_2m_min"]), "tmax": r(hd["temperature_2m_max"]),
                           "snow": r(hd["snowfall_sum"]), "prcp": r(hd["precipitation_sum"])},
                  "fc": {"t0": fd["time"][0], "tmin": r(fd["temperature_2m_min"]), "tmax": r(fd["temperature_2m_max"]),
                         "snow": r(fd["snowfall_sum"]), "prcp": r(fd["precipitation_sum"]), "wind": r(fd["wind_speed_10m_max"])}})
out = {"source": "Open-Meteo.com (ERA5 reanalysis archive + forecast API), CC BY 4.0",
       "fetched": datetime.datetime.now().strftime("%Y-%m-%dT%H:%M"),
       "query": {"archive": ARCHIVE, "forecast": FORECAST, "lat": LAT, "lon": LON, "timezone": TZ}, "cells": cells}
with open("web/js/weather-data.js", "w", encoding="utf-8") as fh:
    fh.write("/* Real weather snapshot. Source: Open-Meteo.com (CC BY 4.0). Generated by data/fetch_weather.py.\n"
             "   Points are public civilian grid points in the western Himalaya, labelled W1-W3; they are not linked to any military site. */\n")
    fh.write("FSI.WEATHER = " + json.dumps(out, separators=(",", ":")) + ";\n")
print("wrote web/js/weather-data.js", out["fetched"])
